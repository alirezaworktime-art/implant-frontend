// Writes docs/STRUCTURE.md: every page, its features and its files in the order they run (from src/**/page.json).
//   node tools/structure.mjs
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..'), SRC = path.join(root, 'src');
const pages = []; const walk = d => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.name === 'page.json') pages.push(p); } }; walk(SRC);
const kb = n => (n / 1024).toFixed(1) + ' KB';
const out = ['# Source structure (generated by `node tools/structure.mjs`)', '',
  'Every page is built from `src/<page>/page.json`: an ordered list of fixed text (the tags), source files and images.',
  'The order is the order the browser runs the code, and it matters: a later file may extend a function of an earlier one.', ''];
for (const j of pages.sort()) {
  const m = JSON.parse(fs.readFileSync(j, 'utf8')), rel = path.relative(SRC, path.dirname(j)).replace(/\\/g, '/');
  const files = m.parts.filter(p => p.file || p.image).map((p, i) => ({ i: i + 1, f: p.file || p.image, size: fs.statSync(path.join(SRC, p.file || p.image)).size }));
  out.push(`## ${m.out} ← \`src/${rel}/\` (${files.length} files, ${kb(files.reduce((s, x) => s + x.size, 0))})`, '');
  const by = {}; for (const x of files) { const k = x.f.split('/').slice(0, -1).join('/'); (by[k] = by[k] || []).push(x); }
  out.push('| folder | files | size |', '|---|---|---|');
  for (const k of Object.keys(by).sort()) out.push(`| \`${k}/\` | ${by[k].length} | ${kb(by[k].reduce((s, x) => s + x.size, 0))} |`);
  out.push('', '<details><summary>All files in run order</summary>', '', '| # | file | size |', '|---|---|---|');
  for (const x of files) out.push(`| ${x.i} | \`${x.f}\` | ${kb(x.size)} |`);
  out.push('', '</details>', '');
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true }); fs.writeFileSync(path.join(root, 'docs', 'STRUCTURE.md'), out.join('\n') + '\n');
console.log('docs/STRUCTURE.md written');
